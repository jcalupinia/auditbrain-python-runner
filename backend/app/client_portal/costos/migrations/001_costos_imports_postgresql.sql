BEGIN;

CREATE TABLE IF NOT EXISTS costos_imports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id INTEGER NOT NULL REFERENCES organizations(id),
  client_id INTEGER NOT NULL REFERENCES clients(id),
  project_id INTEGER NOT NULL REFERENCES projects(id),
  slot VARCHAR(80) NOT NULL,
  checksum VARCHAR(64) NOT NULL,
  original_filename VARCHAR(255) NOT NULL,
  row_count INTEGER NOT NULL DEFAULT 0 CHECK (row_count >= 0),
  CONSTRAINT uq_costos_import_identity UNIQUE (organization_id, client_id, project_id, slot, checksum)
);

CREATE TABLE IF NOT EXISTS costos_import_rows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_id BIGINT NOT NULL REFERENCES costos_imports(id) ON DELETE CASCADE,
  line_number INTEGER NOT NULL CHECK (line_number > 0),
  payload TEXT NOT NULL,
  CONSTRAINT uq_costos_import_line UNIQUE (import_id, line_number)
);

CREATE INDEX IF NOT EXISTS ix_costos_import_tenant ON costos_imports
 (organization_id, client_id, project_id, id);
CREATE INDEX IF NOT EXISTS ix_costos_rows_lookup ON costos_import_rows
 (import_id, line_number);

COMMIT;
